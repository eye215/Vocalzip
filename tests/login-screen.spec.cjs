const {test,expect}=require('@playwright/test');

test('Login and separate signup screen keep account actions usable',async({page})=>{
  await page.route('**/supabase.min.js',route=>route.fulfill({contentType:'application/javascript',body:`window.__signupCalls=[];window.supabase={createClient:()=>({auth:{getUser:async()=>({data:{user:null}}),getSession:async()=>({data:{session:null}}),onAuthStateChange:()=>({data:{subscription:{unsubscribe(){}}}}),signInWithPassword:async()=>({error:{message:'Invalid login credentials'}}),signUp:async(args)=>{window.__signupCalls.push(args);return {data:{session:null},error:null}},resetPasswordForEmail:async()=>({error:null})}})}` }));
  await page.route('**/r2-config.js*',route=>route.fulfill({contentType:'application/javascript',body:"window.VZIP_R2_ENDPOINT='';"}));
  await page.goto('/#/home');
  const screen=page.locator('#vzip-auth-screen');
  await expect(screen).toBeVisible();
  await expect(screen.locator('.vzip-auth-logo')).toHaveText('VOCAL.zip ♫');
  await expect(screen.locator('.vzip-auth-login-card h3')).toHaveText('로그인');
  await expect(screen.locator('.vzip-auth-signup-card')).toBeHidden();
  await expect(screen.locator('label[for=cloud-email]')).toHaveCSS('width','1px');
  await expect(screen.locator('label[for=cloud-password]')).toHaveCSS('width','1px');
  await expect(screen.locator('#cloud-password')).toHaveAttribute('placeholder','비밀번호 8자 이상 입력');
  await expect(screen.getByRole('button',{name:'로그인',exact:true})).toBeVisible();
  await expect(screen.getByRole('button',{name:'비밀번호를 잊으셨나요?'})).toBeVisible();
  await expect(screen.locator('#cloud-signup')).toBeVisible();
  const layout=await screen.evaluate(root=>{const bounds=sel=>root.querySelector(sel).getBoundingClientRect();return {gap:bounds('#cloud-password').top-bounds('#cloud-email').bottom,resetBelow:bounds('#cloud-reset').top>bounds('#cloud-login').bottom}});
  expect(layout.gap).toBeLessThanOrEqual(12);expect(layout.resetBelow).toBe(true);
  if(process.env.VZ_QA_OUTPUT)await page.screenshot({path:process.env.VZ_QA_OUTPUT+'/login-screen.png'});
  await screen.locator('#cloud-email').fill('test@example.com');
  await screen.locator('#cloud-password').fill('password123');
  await screen.getByRole('button',{name:'로그인',exact:true}).click();
  await expect(screen.locator('#vzip-auth-message')).toContainText('이메일 또는 비밀번호가 맞지 않아요');
  await screen.getByRole('button',{name:'비밀번호를 잊으셨나요?'}).click();
  await expect(screen.locator('#vzip-auth-message')).toContainText('재설정 메일을 확인');
  await screen.locator('#cloud-signup').click();
  await expect(screen.locator('.vzip-auth-login-card')).toBeHidden();
  await expect(screen.locator('.vzip-auth-signup-card')).toBeVisible();
  if(process.env.VZ_QA_OUTPUT)await page.screenshot({path:process.env.VZ_QA_OUTPUT+'/signup-screen.png'});
  await expect(screen.locator('#cloud-signup-email')).toHaveValue('test@example.com');
  expect(await page.evaluate(()=>window.__signupCalls.length)).toBe(0);
  await screen.locator('#cloud-signup-password').fill('password123');
  await screen.locator('#cloud-signup-confirm').fill('different123');
  await screen.locator('#cloud-signup-submit').click();
  await expect(screen.locator('#vzip-auth-message')).toContainText('일치하지 않아요');
  expect(await page.evaluate(()=>window.__signupCalls.length)).toBe(0);
  await screen.locator('#cloud-signup-confirm').fill('password123');
  await screen.locator('#cloud-signup-submit').click();
  await expect(screen.locator('#vzip-auth-message')).toContainText('가입 요청 완료');
  expect(await page.evaluate(()=>window.__signupCalls.length)).toBe(1);
  await screen.locator('#cloud-back-login').click();
  await expect(screen.locator('.vzip-auth-login-card')).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
});
